window.renderInfluenciadoresModule = function() {
  const topContainer = document.getElementById("top-10-influenciadores-grid");
  const data = window.INFLUENCIADORES_SJC_DATA;

  if (!data) return;

  // Render Top 10
  if (topContainer) {
    topContainer.innerHTML = data.top10.map(inf => {
      const isTop2 = inf.rank === "01" || inf.rank === "02";
      const ringClass = isTop2 ? "ring-2 ring-accent-cyan ring-offset-2 ring-offset-slate-900" : "ring-2 ring-purple-400/50";
      const bgClass = isTop2 ? "bg-gradient-to-br from-brand-950 to-brand-900 text-white border-brand-700 shadow-md" : "bg-white text-slate-900 border-slate-200 hover:border-purple-300";
      const localAvatar = `fotos_influenciadores/${inf.handle}.jpg`;
      const uiAvatarFallback = `https://ui-avatars.com/api/?name=${encodeURIComponent(inf.name)}&background=0B2545&color=00B4D8&bold=true`;

      return `
        <a href="${inf.url}" target="_blank" rel="noopener noreferrer" class="group p-3.5 rounded-2xl border ${bgClass} shadow-card hover:shadow-card-hover transition-all flex flex-col justify-between space-y-3 cursor-pointer">
          <div class="flex items-center justify-between">
            <span class="text-[10px] font-black font-mono px-2 py-0.5 rounded-full ${isTop2 ? 'bg-accent-cyan/20 text-accent-cyan border border-accent-cyan/40' : 'bg-purple-100 text-purple-800'}">
              #${inf.rank}
            </span>
            <i class="fa-brands fa-instagram text-sm opacity-80 group-hover:opacity-100 group-hover:scale-110 transition-all ${isTop2 ? 'text-accent-cyan' : 'text-purple-600'}"></i>
          </div>

          <div class="flex items-center gap-3">
            <div class="relative shrink-0">
              <img 
                src="${localAvatar}" 
                alt="${inf.name}" 
                onerror="this.onerror=null; this.src='${uiAvatarFallback}';" 
                class="w-11 h-11 rounded-full object-cover shadow-sm ${ringClass}"
              />
            </div>
            <div class="min-w-0 flex-1">
              <h5 class="text-xs font-black truncate leading-tight group-hover:text-accent-cyan transition-colors">${inf.name}</h5>
              <p class="text-[10px] font-semibold opacity-70 truncate">@${inf.handle}</p>
            </div>
          </div>

          ${inf.desc ? `<p class="text-[10px] opacity-75 line-clamp-2 leading-tight font-medium">${inf.desc}</p>` : ''}
        </a>
      `;
    }).join('');
  }

  // Render Stakeholders
  window.filterStakeholdersList();
};

window.filterStakeholdersList = function() {
  const container = document.getElementById("stakeholders-influenciadores-grid");
  const input = document.getElementById("search-stakeholders-input");
  const countEl = document.getElementById("stakeholders-count-badge");
  const data = window.INFLUENCIADORES_SJC_DATA;

  if (!container || !data) return;

  const query = (input?.value || "").toLowerCase().trim();
  const filtered = data.stakeholders.filter(s => {
    return s.name.toLowerCase().includes(query) || s.handle.toLowerCase().includes(query);
  });

  if (countEl) countEl.textContent = `${filtered.length} Perfis`;

  if (filtered.length === 0) {
    container.innerHTML = `
      <div class="col-span-full p-6 text-center text-slate-400 text-xs font-medium">
        Nenhum influenciador encontrado para "${query}".
      </div>
    `;
    return;
  }

  container.innerHTML = filtered.map(st => {
    const localAvatar = `fotos_influenciadores/${st.handle}.jpg`;
    const uiAvatarFallback = `https://ui-avatars.com/api/?name=${encodeURIComponent(st.name)}&background=0B2545&color=00B4D8&bold=true`;
    return `
      <a href="${st.url}" target="_blank" rel="noopener noreferrer" class="group flex items-center gap-2.5 p-2 rounded-xl bg-white hover:bg-slate-100 border border-slate-200/80 hover:border-brand-400 transition-all shadow-2xs">
        <img 
          src="${localAvatar}" 
          alt="${st.name}" 
          onerror="this.onerror=null; this.src='${uiAvatarFallback}';" 
          class="w-8 h-8 rounded-full object-cover shrink-0 ring-1 ring-slate-200"
        />
        <div class="min-w-0 flex-1">
          <p class="text-[11px] font-bold text-slate-900 truncate leading-tight group-hover:text-brand-900">${st.name}</p>
          <p class="text-[9px] font-medium text-slate-400 truncate">@${st.handle}</p>
        </div>
        <i class="fa-solid fa-arrow-up-right-from-square text-[9px] text-slate-300 group-hover:text-brand-600 shrink-0 mr-1"></i>
      </a>
    `;
  }).join('');
};

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", window.renderInfluenciadoresModule);
} else {
  setTimeout(window.renderInfluenciadoresModule, 50);
}
